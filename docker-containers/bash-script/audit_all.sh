#!/usr/bin/env bash
# Аудит всех контейнеров по чек-листу.
# Запуск: sudo ./audit.sh
# Результат: ./audit_reports/report_<date>.txt

set -u

CONTAINERS=(
  "***"
  "***"
  "***"
  "***"
  "***"
  "***"
  "***"
)

REPORT_DIR="./audit_reports"
DATE=$(date +%Y-%m-%d_%H-%M-%S)
REPORT="$REPORT_DIR/report_${DATE}.txt"
mkdir -p "$REPORT_DIR"

# Функция проверки. Вызывается из checklist.sh.
# $1 — раздел, $2 — название проверки, $3 — команда
check() {
  local section="$1" title="$2" cmd="$3"

  {
    echo ""
    echo "=============================================================="
    echo "  $section — $title"
    echo "=============================================================="
    echo "📋 Команда:"
    echo "   $cmd"
    echo ""

    for c in "${CONTAINERS[@]}"; do
      echo "── $c ──"
      docker exec "$c" bash -c "$cmd" 2>&1 | sed 's/^/   /'
      echo ""
    done
  } >> "$REPORT"
}

# Заголовок
{
  echo "=============================================================="
  echo "  СВОДНЫЙ ОТЧЁТ О ПРОВЕРКЕ"
  echo "=============================================================="
  echo "Дата:   $(date '+%Y-%m-%d %H:%M:%S')"
  echo "Хосты:  ${CONTAINERS[*]}"
  echo "=============================================================="
} > "$REPORT"

# Подключаем чек-лист — он вызовет check нужное число раз
source ./checklist.sh

echo ""
echo "=============================================================="
echo "  АУДИТ ЗАВЕРШЁН"
echo "  Отчёт: $REPORT"
echo "=============================================================="